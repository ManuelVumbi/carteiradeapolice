export const SUPPORTED_IMPORT_EXTENSIONS = [
  '.pdf',
  '.docx',
  '.doc',
  '.png',
  '.jpg',
  '.jpeg',
  '.webp',
  '.gif',
  '.xlsx',
  '.xls',
  '.csv',
  '.txt',
] as const;

export const MAX_UPLOAD_BYTES = 15 * 1024 * 1024; // 15 MB

export function getFileExtension(fileName: string): string {
  const idx = fileName.lastIndexOf('.');
  return idx >= 0 ? fileName.slice(idx).toLowerCase() : '';
}

export function isSupportedPolicyFile(fileName: string, mimeType: string): boolean {
  const ext = getFileExtension(fileName);
  if (
    SUPPORTED_IMPORT_EXTENSIONS.includes(
      ext as (typeof SUPPORTED_IMPORT_EXTENSIONS)[number]
    )
  ) {
    return true;
  }
  const mime = (mimeType || '').toLowerCase();
  return (
    mime === 'application/pdf' ||
    mime.startsWith('image/') ||
    mime.includes('wordprocessingml') ||
    mime.includes('msword') ||
    mime.includes('spreadsheetml') ||
    mime === 'text/csv' ||
    mime === 'text/plain'
  );
}

/**
 * Converts HTML generated by Mammoth (.docx) into clean structured text,
 * preserving table rows and pipe-separated columns for accurate LLM extraction.
 */
export function htmlTablesToStructuredText(html: string): string {
  if (!html) return '';
  let out = html
    .replace(/<\/tr>/gi, '\n')
    .replace(/<\/(td|th)>/gi, ' | ')
    .replace(/<\/(p|div|h1|h2|h3|h4|h5|h6|li|br\s*\/?)>/gi, '\n')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, ' ');

  out = out
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/gi, "'");

  return out
    .split('\n')
    .map((line) => line.replace(/[ \t]+/g, ' ').replace(/\s*\|\s*/g, ' | ').trim())
    .filter((line) => line.length > 0 && line !== '|')
    .join('\n');
}
